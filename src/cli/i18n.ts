export const messages: Record<Lang, Messages> = { ja, en }

export function detectLang(env: Record<string, string | undefined> = process.env): Lang {
  const l = env.LC_ALL || env.LC_MESSAGES || env.LANG || Intl.DateTimeFormat().resolvedOptions().locale || ''
  return /^ja/i.test(l) ? 'ja' : 'en'
}
