const NAME = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/

export const defaultRunner: Runner = (cmd, args, { cwd, capture, env }) =>
  new Promise((done, fail) => {
    const child = spawn(cmd, args, {
      cwd,
      env: { ...process.env, ...env },
      stdio: capture ? ['inherit', 'pipe', 'inherit'] : 'inherit',
      shell: process.platform === 'win32',
    })
    let stdout = ''
    child.stdout?.on('data', (d: Buffer) => {
      stdout += d.toString()
      process.stdout.write(d)
    })
    child.on('error', fail)
    child.on('close', (code) => done({ code: code ?? 1, stdout }))
  })

/** The compiled Worker shipped in this package. */
export function workerEntry(): string {
  return fileURLToPath(new URL('../relay/worker.js', import.meta.url))
}

export function kindsVar(kinds: string | undefined): string {
  const k = (kinds ?? 'anodb').trim()
  if (k === 'anodb') return ANODB_KINDS.join(',')
  if (k === '*') return '*'
  const list = k.split(',').map((s) => s.trim())
  if (list.length === 0 || !list.every((s) => /^\d{1,5}$/.test(s))) throw new Error('--kinds must be anodb, * or a comma-separated list of kinds')
  return list.join(',')
}

/** wrangler.toml for the relay. `main` is relative so the folder can be committed. */
export function wranglerToml(name: string, dir: string, entry: string, kinds: string): string {
  const main = relative(dir, entry).split(sep).join('/')
  return `# Generated by \`anodb relay deploy\`. Re-running the command rewrites this file.
name = "${name}"
main = "${main}"
compatibility_date = "${COMPATIBILITY_DATE}"
workers_dev = true

[vars]
RELAY_KINDS = "${kinds}"

[[durable_objects.bindings]]
name = "RELAY"
class_name = "Relay"

# SQLite-backed Durable Object: events live in its SQL storage and survive redeploys.
[[migrations]]
tag = "v1"
new_sqlite_classes = ["Relay"]
`
}

/** The relay URL from wrangler's deploy output (https://<name>.<account>.workers.dev → wss://…). */
export function relayUrlFrom(output: string): string | null {
  const m = /https:\/\/[a-z0-9-]+(?:\.[a-z0-9-]+)*\.workers\.dev\b/i.exec(output)
  return m ? m[0].replace(/^https:/, 'wss:') : null
}

function prepare(flags: RelayFlags, cwd: string) {
  const dir = resolve(cwd, flags.dir ?? '.anodb/relay')
  mkdirSync(dir, { recursive: true })
  const stateFile = join(dir, 'relay.json')
  const prev: RelayState | null = existsSync(stateFile) ? (JSON.parse(readFileSync(stateFile, 'utf8')) as RelayState) : null
  const name = flags.name ?? prev?.name ?? 'anodb-relay'
  if (!NAME.test(name)) throw new Error(`invalid Worker name "${name}" (lowercase letters, digits and -)`)
  const config = join(dir, 'wrangler.toml')
  writeFileSync(config, wranglerToml(name, dir, workerEntry(), kindsVar(flags.kinds)))
  // wrangler keeps local dev state and build output next to the config.
  const ignore = join(dir, '.gitignore')
  if (!existsSync(ignore)) writeFileSync(ignore, '.wrangler/\ndist/\n')
  return { dir, stateFile, prev, name, config }
}

export async function runRelay(
  sub: string | undefined,
  flags: RelayFlags,
  { cwd, run = defaultRunner, log = console.log }: { cwd: string; run?: Runner; log?: (s: string) => void },
): Promise<RelayState | null> {
  const m = t[flags.lang ?? detectLang()]
  const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx'
  const wrangler = (args: string[], capture = false) => run(npx, ['--yes', WRANGLER, ...args], { cwd, capture })

  if (sub === 'dev') {
    const { config } = prepare(flags, cwd)
    const port = flags.port ?? 8787
    log(m.dev(port))
    const r = await wrangler(['dev', '--config', config, '--port', String(port)])
    if (r.code !== 0) throw new Error(m.failed(r.code))
    return null
  }
  if (sub !== 'deploy') throw new Error('usage: anodb relay deploy | anodb relay dev')

  const { dir, stateFile, prev, name, config } = prepare(flags, cwd)
  if (flags.dryRun) {
    const out = join(dir, 'dist')
    const r = await wrangler(['deploy', '--config', config, '--dry-run', '--outdir', out])
    if (r.code !== 0) throw new Error(m.failed(r.code))
    log(m.dryRun(out))
    return { name }
  }
  // CI can use CLOUDFLARE_API_TOKEN; otherwise make sure there is a login (browser OAuth).
  if (!process.env.CLOUDFLARE_API_TOKEN) {
    const who = await wrangler(['whoami'], true)
    if (who.code !== 0 || /not authenticated|wrangler login/i.test(who.stdout)) {
      log(m.login)
      const l = await wrangler(['login'])
      if (l.code !== 0) throw new Error(m.failed(l.code))
    }
  }
  log(m.deploying(name))
  const r = await wrangler(['deploy', '--config', config], true)
  if (r.code !== 0) throw new Error(m.failed(r.code))
  const url = relayUrlFrom(r.stdout) ?? prev?.url
  const state: RelayState = { name, ...(url ? { url } : {}), deployedAt: new Date().toISOString() }
  mkdirSync(dirname(stateFile), { recursive: true })
  writeFileSync(stateFile, `${JSON.stringify(state, null, 2)}\n`)
  if (url) {
    log(m.done(url))
    log(m.use(url))
  } else log(m.noUrl)
  log(m.again)
  return state
}
